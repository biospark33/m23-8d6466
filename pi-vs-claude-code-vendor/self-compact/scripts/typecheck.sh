#!/usr/bin/env bash
# Typecheck against the globally installed Pi packages, wherever npm put them.
#
# This repo has no node_modules: Pi's loader supplies its packages at runtime and Node 24 strips
# types for the tests. Only tsc needs to be told where Pi's type declarations live, and that path
# differs per machine, so it is resolved here into tsconfig.tsc.json (gitignored) which extends
# the checked-in tsconfig.json.
#
# Override the location with PI_DIR=/path/to/@earendil-works/pi-coding-agent
set -euo pipefail
cd "$(dirname "$0")/.."

PI_DIR="${PI_DIR:-$(npm root -g)/@earendil-works/pi-coding-agent}"
# pi >=1.x left the global npm tree — fall back to the pi-managed release
# layout, the same source tests/parity resolves. Only releases that actually
# carry dist/ are candidates, so an incomplete newest release cannot block an
# older usable one.
release_dir="$(ls -d "$HOME"/.pi/agent/install/releases/*/node_modules/@earendil-works/pi-coding-agent/dist 2>/dev/null | sed 's:/dist$::' | sort -V | tail -1 || true)"
if [ ! -d "$PI_DIR/dist" ] && [ -n "$release_dir" ] && [ -d "$release_dir/dist" ]; then
	PI_DIR="$release_dir"
fi
if [ ! -d "$PI_DIR/dist" ]; then
	echo "Pi types not found at: $PI_DIR" >&2
	echo "Install Pi with: npm install -g --ignore-scripts @earendil-works/pi-coding-agent" >&2
	echo "Or point PI_DIR at an existing installation." >&2
	exit 1
fi

# npm installs Pi as a package with nested node_modules; the pi-managed release
# layout is flat — its node_modules sits two levels above the package dir
# (<release>/node_modules/@earendil-works/pi-coding-agent).
NM_DIR="${PI_DIR}/node_modules"
[ -d "$NM_DIR" ] || NM_DIR="$(dirname "$(dirname "$PI_DIR")")"

node --input-type=module -e '
import { writeFileSync } from "node:fs";
const pi = process.argv[1];
const nm = process.argv[2];
const config = {
	"//": "Generated by scripts/typecheck.sh. Do not edit; edit tsconfig.json instead.",
	extends: "./tsconfig.json",
	compilerOptions: {
		typeRoots: [`${nm}/@types`],
		paths: {
			"@earendil-works/pi-coding-agent": [`${pi}/dist/index.d.ts`],
			"@earendil-works/pi-ai": [`${nm}/@earendil-works/pi-ai/dist/index.d.ts`],
			"@earendil-works/pi-tui": [`${nm}/@earendil-works/pi-tui/dist/index.d.ts`],
			"@earendil-works/pi-agent-core": [`${nm}/@earendil-works/pi-agent-core/dist/index.d.ts`],
			typebox: [`${nm}/typebox/build/index.d.mts`],
		},
	},
};
writeFileSync("tsconfig.tsc.json", `${JSON.stringify(config, null, "\t")}\n`);
' "$PI_DIR" "$NM_DIR"

exec npx -y -p typescript tsc --noEmit -p tsconfig.tsc.json
